// Command gen writes names_gen.go in the layout package: for each read of a bits.SliceReader in the mp4 package
// of mp4ff, the name of the field that the read sets, taken from the source code.
//
// It runs from the layout package with go generate, and reads the source of the mp4ff version in go.mod.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

// readMethods are the methods of bits.SliceReader that consume bytes.
var readMethods = map[string]bool{
	"ReadUint8": true, "ReadUint16": true, "ReadInt16": true, "ReadUint24": true, "ReadUint32": true,
	"ReadInt32": true, "ReadUint64": true, "ReadInt64": true, "ReadFixedLengthString": true,
	"ReadZeroTerminatedString": true, "ReadPossiblyZeroTerminatedString": true, "ReadBytes": true,
	"RemainingBytes": true, "SkipBytes": true,
}

// entry is the name of a read.
type entry struct {
	method    string
	name      string
	quickTime bool
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func run() error {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}} {{.Version}}", "github.com/Eyevinn/mp4ff").Output()
	if err != nil {
		return fmt.Errorf("go list: %w", err)
	}
	dir, version, _ := strings.Cut(strings.TrimSpace(string(out)), " ")
	entries, err := parseDir(filepath.Join(dir, "mp4"))
	if err != nil {
		return err
	}
	keys := make([]string, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Slice(keys, func(i, j int) bool { return lessKey(keys[i], keys[j]) })
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./gen from the mp4 package of mp4ff %s; DO NOT EDIT.\n\n", version)
	b.WriteString("package layout\n\n")
	b.WriteString("var readNames = map[string]readName{\n")
	for _, k := range keys {
		e := entries[k]
		fmt.Fprintf(&b, "\t%q: {%q, %q, %t},\n", k, e.method, e.name, e.quickTime)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("names_gen.go", src, 0o644)
}

// lessKey orders keys such as "mp4/tkhd.go:80" by file and then by line.
func lessKey(a, b string) bool {
	fa, la, _ := strings.Cut(a, ":")
	fb, lb, _ := strings.Cut(b, ":")
	if fa != fb {
		return fa < fb
	}
	return len(la) < len(lb) || len(la) == len(lb) && la < lb
}

func parseDir(dir string) (map[string]entry, error) {
	fset := token.NewFileSet()
	entries := map[string]entry{}
	err := filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() && path != dir {
			return filepath.SkipDir
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		f, err := parser.ParseFile(fset, path, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		addFile(fset, f, "mp4/"+filepath.Base(path), entries)
		return nil
	})
	return entries, err
}

// addFile adds the reads in f. A read gets the name of what it is assigned to, or the comment on its line.
// A line with more than one read gets no name, since the reads cannot be told apart at run time.
func addFile(fset *token.FileSet, f *ast.File, file string, entries map[string]entry) {
	comments := map[int]string{}
	for _, cg := range f.Comments {
		c := cg.List[0]
		if strings.HasPrefix(c.Text, "//") {
			comments[fset.Position(c.Pos()).Line] = strings.TrimSpace(strings.TrimPrefix(c.Text, "//"))
		}
	}
	perLine := map[string]int{}
	var stack []ast.Node
	ast.Inspect(f, func(n ast.Node) bool {
		if n == nil {
			stack = stack[:len(stack)-1]
			return true
		}
		stack = append(stack, n)
		call, ok := n.(*ast.CallExpr)
		if !ok {
			return true
		}
		sel, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || !readMethods[sel.Sel.Name] {
			return true
		}
		line := fset.Position(call.Pos()).Line
		key := fmt.Sprintf("%s:%d", file, line)
		perLine[key]++
		name, qt := target(stack)
		if name == "" {
			name = comments[line]
		}
		e := entry{method: sel.Sel.Name, name: name, quickTime: qt || strings.Contains(name, "QuickTime")}
		if perLine[key] > 1 {
			e = entry{method: "", name: ""}
		}
		entries[key] = e
		return true
	})
}

// target returns the name of what the call at the top of stack is assigned to, and whether it is in a
// QuickTime structure.
func target(stack []ast.Node) (string, bool) {
	call := stack[len(stack)-1]
	for i := len(stack) - 2; i >= 0; i-- {
		switch s := stack[i].(type) {
		case *ast.AssignStmt:
			idx := 0
			if len(s.Lhs) == len(s.Rhs) {
				for j, r := range s.Rhs {
					if contains(r, call) {
						idx = j
					}
				}
			}
			return fieldName(s.Lhs[idx]), false
		case *ast.ValueSpec:
			idx := 0
			for j, v := range s.Values {
				if contains(v, call) {
					idx = j
				}
			}
			if idx < len(s.Names) {
				return s.Names[idx].Name, false
			}
			return "", false
		case *ast.KeyValueExpr:
			if !contains(s.Value, call) {
				continue
			}
			qt := false
			if i > 0 {
				if lit, ok := stack[i-1].(*ast.CompositeLit); ok {
					qt = strings.Contains(exprString(lit.Type), "QuickTime")
				}
			}
			return exprString(s.Key), qt
		case *ast.FuncDecl, *ast.FuncLit, *ast.BlockStmt, *ast.ReturnStmt, *ast.IfStmt, *ast.ExprStmt:
			return "", false
		}
	}
	return "", false
}

func contains(root, n ast.Node) bool {
	found := false
	ast.Inspect(root, func(x ast.Node) bool {
		if x == n {
			found = true
		}
		return !found
	})
	return found
}

// fieldName returns the name of an assignment target, without the variable that holds the struct, such as
// "TrackID" for t.TrackID, and with "[]" for an index, such as "Matrix[]" for t.Matrix[i].
func fieldName(e ast.Expr) string {
	s := exprString(e)
	if _, rest, ok := strings.Cut(s, "."); ok && !strings.HasPrefix(s, "[") {
		s = rest
	}
	return s
}

func exprString(e ast.Expr) string {
	switch x := e.(type) {
	case *ast.Ident:
		return x.Name
	case *ast.SelectorExpr:
		return exprString(x.X) + "." + x.Sel.Name
	case *ast.IndexExpr:
		return exprString(x.X) + "[]"
	case *ast.StarExpr:
		return exprString(x.X)
	case *ast.ParenExpr:
		return exprString(x.X)
	}
	return ""
}
